def marigold():
    out = grass() + stem('M200,220 C196,280 204,330 200,372') + [leaf(200, 290, -150, 0.85), leaf(200, 320, -30, 0.85)]
    for r, f in [(110, 'o'), (84, 'gold'), (58, 'o'), (32, 'gold')]:
        n = max(8, int(r / 6))
        pts = []
        for i in range(n * 2):
            rr = r if i % 2 == 0 else r - 14
            a = math.radians(i * 180 / n)
            pts.append(f'{200 + rr*math.cos(a):.1f},{150 + rr*0.92*math.sin(a):.1f}')
        out.append(P('M' + ' Q'.join(f'{pts[i]} {pts[i+1]}' for i in range(0, len(pts) - 1, 2)) + ' Z', f))
    return out


