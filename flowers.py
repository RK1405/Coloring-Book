def tube(d, w, f):
    return [P(d, 'none', w + 2 * SW), P(d, 'none', w).replace('#1a1a1a', fc(f))]


def stem(d, w=14):
    return tube(d, w, 'g')


def leaf(x, y, rot, s=1.0, f='g'):
    return G([P(f'M0,0 C{20*s},{-24*s} {62*s},{-24*s} {86*s},0 C{62*s},{24*s} {20*s},{24*s} 0,0 Z', f),
              L(f'M6,0 Q{40*s},{-4*s} {72*s},0', 4)], f'translate({x},{y}) rotate({rot})')


def petal_ring(cx, cy, n, l, w, f, rot0=0, start=0, sw=SW, notch=False):
    out = []
    for i in range(n):
        a = rot0 + i * 360 / n
        if notch:
            d = f'M0,{-start} C{-w},{-start-l*0.3} {-w},{-start-l} {-w*0.3},{-start-l} L0,{-start-l*0.85} L{w*0.3},{-start-l} C{w},{-start-l} {w},{-start-l*0.3} 0,{-start} Z'
        else:
            d = f'M0,{-start} C{-w},{-start-l*0.3} {-w*0.8},{-start-l} 0,{-start-l} C{w*0.8},{-start-l} {w},{-start-l*0.3} 0,{-start} Z'
        out.append(G([P(d, f, sw)], f'translate({cx},{cy}) rotate({a:.1f})'))
    return out


def face(cx, cy, s=1.0):
    return [eye(cx - 16 * s, cy - 6 * s, 0.8 * s), eye(cx + 16 * s, cy - 6 * s, 0.8 * s),
            smile(cx, cy + 10 * s, 12 * s, 6 * s), blush(cx - 28 * s, cy + 8 * s, 8 * s, 5 * s), blush(cx + 28 * s, cy + 8 * s, 8 * s, 5 * s)]


